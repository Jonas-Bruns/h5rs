use std::error::Error;
use std::hint::black_box;
use std::ops::Range;
use std::time::Instant;

use h5rs::{Dataset, H5File, Limits, ReadPool};

fn main() -> Result<(), Box<dyn Error>> {
    let Some(path) = std::env::args_os().nth(1) else {
        eprintln!("Usage: cargo bench --bench read_tiles -- path-to-fixture.h5");
        return Ok(());
    };
    // Libtest tooling may invoke every bench target even when no HDF5 path was supplied.
    if path.to_string_lossy().starts_with("--") {
        return Ok(());
    }
    let backend = if cfg!(feature = "simd-deflate") {
        "zlib-rs"
    } else {
        "miniz_oxide"
    };
    for threads in [1, 2, 4, 8] {
        let pool = ReadPool::new(threads, 1)?;
        let file = H5File::open_with_pool(&path, Limits::default(), pool)?;
        for name in ["deflate", "shuffle_deflate"] {
            let dataset = file.dataset(name)?;
            let shape = &dataset.metadata().shape;
            if *shape != [4096, 4096] || dataset.metadata().chunks != [256, 256] {
                return Err("use a fixture generated by benches/make_fixture.py".into());
            }
            for tile_size in [256_u64, 512] {
                let selections = selections(tile_size);
                for ranges in &selections {
                    black_box(dataset.read_region(ranges)?);
                }
                let (reads_per_sec, mib_per_sec, p50, p95, p99) = measure(&dataset, &selections)?;
                println!(
                    "{{\"backend\":\"{backend}\",\"dataset\":\"{name}\",\"threads\":{threads},\"tile_size\":{tile_size},\"requests\":{},\"reads_per_sec\":{reads_per_sec:.2},\"mib_per_sec\":{mib_per_sec:.2},\"p50_us\":{p50:.2},\"p95_us\":{p95:.2},\"p99_us\":{p99:.2}}}",
                    selections.len(),
                );
            }
        }
    }
    Ok(())
}

fn selections(tile_size: u64) -> Vec<[Range<u64>; 2]> {
    (0..256)
        .map(|index| {
            // A reproducible spread of locations. The 256 tiles are one full
            // chunk; the 512 tiles are misaligned and intersect nine chunks.
            let (y, x) = if tile_size == 256 {
                ((index * 113 / 16 % 16) * 256, (index * 113 % 16) * 256)
            } else {
                let unaligned = |value| {
                    let offset = value % (14 * 255);
                    offset / 255 * 256 + offset % 255 + 1
                };
                (unaligned(index * 631), unaligned(index * 941))
            };
            [y..y + tile_size, x..x + tile_size]
        })
        .collect()
}

fn measure(
    dataset: &Dataset,
    selections: &[[Range<u64>; 2]],
) -> Result<(f64, f64, f64, f64, f64), h5rs::Error> {
    let mut timings = Vec::with_capacity(selections.len());
    let mut bytes = 0_usize;
    let start = Instant::now();
    for ranges in selections {
        let request = Instant::now();
        let result = black_box(dataset.read_region(ranges)?);
        timings.push(request.elapsed());
        bytes += result.bytes.len();
    }
    let seconds = start.elapsed().as_secs_f64();
    timings.sort_unstable();
    let percentile = |percent: usize| {
        timings[(timings.len() * percent).div_ceil(100) - 1].as_secs_f64() * 1_000_000.0
    };
    Ok((
        timings.len() as f64 / seconds,
        bytes as f64 / (1024.0 * 1024.0) / seconds,
        percentile(50),
        percentile(95),
        percentile(99),
    ))
}
